import { useMemo, useState } from "react";
import { useSearchParams } from "react-router-dom";
import { balances, unallocated } from "@/ar/engine/analytics";
import { round2 } from "@/ar/engine/dates";
import { suggestMatch, type BankLine } from "@/ar/engine/importer";
import type { ArBook, ArPayment } from "@/ar/engine/types";
import { arService, today, useAction, useArBook } from "@/ar/ui/hooks";
import { ArPage, EmptyLedger, Feedback, Field, SmallButton, Table, Tag, money, nameMaps } from "@/ar/ui/kit";
import { Button, Notice, Section, inputClass } from "@/integrations/ui/components";
import { download, useAsync } from "@/integrations/ui/hooks";

function receiptHtml(book: ArBook, payment: ArPayment): string {
  const { tenantName } = nameMaps(book);
  const invoices = new Map(book.invoices.map((invoice) => [invoice.id, invoice]));
  const rows = payment.allocations.map((item) => `<tr><td>${invoices.get(item.invoiceId)?.number ?? ""}</td><td>${item.date}</td><td style="text-align:right">${money(item.amount, payment.currency)}</td></tr>`).join("");
  const left = unallocated(payment);
  const esc = (value: string) => value.replace(/[&<>"]/g, (char) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[char] ?? char);
  return `<!doctype html><html><head><meta charset="utf-8"><title>Receipt ${payment.number}</title><style>body{font-family:Georgia,serif;max-width:640px;margin:40px auto;color:#0B1D33}td,th{border-bottom:1px solid #ddd;padding:6px;text-align:left}table{width:100%;border-collapse:collapse}</style></head><body><h1>Receipt ${payment.number}</h1><p>Received from <b>${esc(tenantName(payment.tenantId))}</b> on ${payment.receivedDate}</p><p>Amount: <b>${money(payment.amount, payment.currency)}</b> · ${esc(payment.method)} ${esc(payment.reference)} · ${esc(payment.bankAccount)}</p><p>Legal entity: ${esc(payment.entityId)}</p><table><thead><tr><th>Invoice</th><th>Applied</th><th style="text-align:right">Amount</th></tr></thead><tbody>${rows}</tbody></table>${left > 0 ? `<p>Unallocated credit on account: ${money(left, payment.currency)}</p>` : ""}${payment.status !== "Posted" ? `<p><b>Status: ${payment.status}</b></p>` : ""}<p style="font-size:12px;color:#666">Generated by EstateCFO from the AR ledger.</p></body></html>`;
}

export function PaymentAllocationPage() {
  const { book, workspaceId } = useArBook();
  const [params] = useSearchParams();
  const action = useAction();
  const [form, setForm] = useState({ tenantId: params.get("tenant") ?? "", date: today(), amount: "", bank: "", method: "Bank transfer", reference: "" });
  const [allocation, setAllocation] = useState<Record<string, string>>({});
  const [applyTo, setApplyTo] = useState<Record<string, { invoiceId: string; amount: string }>>({});
  const [reason, setReason] = useState<Record<string, string>>({});
  const preview = useAsync(async () => (workspaceId ? arService.importPreview(workspaceId) : undefined), [workspaceId]).data;
  const open = useMemo(() => (book ? [...balances(book).values()].filter((balance) => balance.outstanding > 0) : []), [book]);
  if (!book || !workspaceId) return null;
  const { tenantName } = nameMaps(book);
  const tenant = book.tenants.find((item) => item.id === form.tenantId);
  const tenantOpen = open.filter((balance) => balance.invoice.tenantId === form.tenantId).sort((a, b) => a.invoice.dueDate.localeCompare(b.invoice.dueDate));
  const allocated = round2(Object.values(allocation).reduce((sum, value) => sum + (Number(value) || 0), 0));
  const amount = Number(form.amount) || 0;
  const lines = preview?.bankLines ?? [];
  const unapplied = book.payments.filter((payment) => payment.status === "Posted" && unallocated(payment) > 0);

  function oldestFirst() {
    let left = amount;
    const next: Record<string, string> = {};
    for (const balance of tenantOpen) {
      if (left <= 0) break;
      const value = round2(Math.min(left, balance.outstanding));
      next[balance.invoice.id] = String(value);
      left = round2(left - value);
    }
    setAllocation(next);
  }

  async function match(line: BankLine) {
    const suggestion = suggestMatch(book!, line, today());
    if (!suggestion.tenantId) return action.run(async () => { throw new Error(`No match for ${line.reference || line.description}: ${suggestion.reason} Record it manually above with the payer you have confirmed.`); });
    const detail = suggestion.allocations.map((item) => `${book!.invoices.find((invoice) => invoice.id === item.invoiceId)?.number} ${item.amount}`).join(", ") || "nothing (held as unallocated)";
    if (!window.confirm(`Match ${money(line.amount)} on ${line.date} to ${tenantName(suggestion.tenantId)}?\nAllocate to: ${detail}\nBasis: ${suggestion.reason}`)) return;
    await action.run(() => arService.matchBankLine(workspaceId!, line, { tenantId: suggestion.tenantId!, allocations: suggestion.allocations, bankAccount: book!.settings.bankAccounts.find((bank) => bank.name === line.bankAccount)?.name ?? book!.settings.bankAccounts[0].name }), "Bank line matched; receipt and journal created.");
  }

  return (
    <ArPage title="Payment Allocation" subtitle="Record tenant receipts, allocate them to invoices (partially or across several), match imported bank lines, and apply unallocated cash. Every receipt creates a payment record and a journal.">
      <Feedback error={action.error} message={action.message} />
      <EmptyLedger book={book} />
      <Section title="Record a receipt">
        <form
          className="space-y-4"
          onSubmit={async (event) => {
            event.preventDefault();
            const ok = await action.run(() => arService.recordPayment(workspaceId, { tenantId: form.tenantId, receivedDate: form.date, amount, currency: tenant?.currency ?? book.settings.groupCurrency, bankAccount: form.bank || book.settings.bankAccounts[0]?.name, method: form.method, reference: form.reference, allocations: Object.entries(allocation).map(([invoiceId, value]) => ({ invoiceId, amount: Number(value) || 0 })) }), "Receipt recorded and posted.");
            if (ok) {
              setForm({ ...form, amount: "", reference: "" });
              setAllocation({});
            }
          }}
        >
          <div className="grid gap-3 md:grid-cols-3 xl:grid-cols-6">
            <Field label="Tenant"><select aria-label="Receipt tenant" className={`${inputClass} w-full`} value={form.tenantId} onChange={(event) => { setForm({ ...form, tenantId: event.target.value }); setAllocation({}); }}><option value="">Choose tenant</option>{book.tenants.map((item) => <option key={item.id} value={item.id}>{item.code} · {item.name}</option>)}</select></Field>
            <Field label="Received"><input aria-label="Receipt date" type="date" className={`${inputClass} w-full`} value={form.date} onChange={(event) => setForm({ ...form, date: event.target.value })} /></Field>
            <Field label={`Amount${tenant ? ` (${tenant.currency})` : ""}`}><input aria-label="Receipt amount" type="number" step="0.01" className={`${inputClass} w-full`} value={form.amount} onChange={(event) => setForm({ ...form, amount: event.target.value })} /></Field>
            <Field label="Bank account"><select aria-label="Receipt bank" className={`${inputClass} w-full`} value={form.bank} onChange={(event) => setForm({ ...form, bank: event.target.value })}>{book.settings.bankAccounts.map((bank) => <option key={bank.name}>{bank.name}</option>)}</select></Field>
            <Field label="Method"><select aria-label="Receipt method" className={`${inputClass} w-full`} value={form.method} onChange={(event) => setForm({ ...form, method: event.target.value })}>{["Bank transfer", "ACH", "Wire", "Check", "Card", "SEPA", "Cash"].map((method) => <option key={method}>{method}</option>)}</select></Field>
            <Field label="Reference"><input aria-label="Receipt reference" className={`${inputClass} w-full`} value={form.reference} onChange={(event) => setForm({ ...form, reference: event.target.value })} /></Field>
          </div>
          {form.tenantId ? (
            tenantOpen.length === 0 ? <p className="text-sm text-navy/60">{tenant?.name} has no open invoices. The receipt will be held as unallocated cash.</p> : (
              <div>
                <div className="mb-2 flex items-center gap-2"><SmallButton onClick={oldestFirst} disabled={!amount}>Allocate oldest first</SmallButton><SmallButton onClick={() => setAllocation({})}>Clear</SmallButton></div>
                <Table min={700}>
                  <thead><tr><th>Invoice</th><th>Due</th><th className="text-right">Outstanding</th><th className="text-right">Allocate</th></tr></thead>
                  <tbody>{tenantOpen.map((balance) => <tr key={balance.invoice.id}><td className="font-semibold">{balance.invoice.number}</td><td>{balance.invoice.dueDate}</td><td className="text-right tabular-nums">{money(balance.outstanding, balance.invoice.currency)}</td><td className="text-right"><input aria-label={`Allocate to ${balance.invoice.number}`} type="number" step="0.01" min={0} max={balance.outstanding} className={`${inputClass} w-32 text-right`} value={allocation[balance.invoice.id] ?? ""} onChange={(event) => setAllocation({ ...allocation, [balance.invoice.id]: event.target.value })} /></td></tr>)}</tbody>
                </Table>
              </div>
            )
          ) : null}
          <div className="flex flex-wrap items-center gap-4 text-sm">
            <span>Allocated <b>{money(allocated, tenant?.currency)}</b></span>
            <span className={amount - allocated < 0 ? "text-red-700" : ""}>Unallocated <b>{money(round2(amount - allocated), tenant?.currency)}</b></span>
            <Button primary type="submit" disabled={action.busy || !form.tenantId || !amount || allocated > amount}>Post receipt</Button>
          </div>
        </form>
      </Section>

      <Section title={`Bank lines to match (${lines.length})`} subtitle="From published Payment Transactions (receipt exports) and Cash Transactions inflows in Data Integrations. Suggestions use invoice references, tenant codes or names, and exact amounts; you confirm every match.">
        {lines.length === 0 ? <p className="text-sm text-navy/60">No unmatched bank lines. Publish a Payment Transactions or Cash Transactions import to match receipts here.</p> : (
          <Table min={1000}>
            <thead><tr><th>Date</th><th>Source</th><th>Description</th><th>Reference</th><th className="text-right">Amount</th><th>Suggestion</th><th /></tr></thead>
            <tbody>
              {lines.map((line) => {
                const suggestion = suggestMatch(book, line, today());
                return (
                  <tr key={line.key}>
                    <td>{line.date}</td>
                    <td className="text-xs">{line.kind}<span className="block text-navy/50">{line.source.system}</span></td>
                    <td>{line.description || "—"}</td>
                    <td>{line.reference}{line.invoiceRef ? ` · ${line.invoiceRef}` : ""}</td>
                    <td className="text-right tabular-nums">{money(line.amount)}</td>
                    <td className="text-xs"><Tag tone={suggestion.confidence === "high" ? "Posted" : suggestion.confidence === "medium" ? "Approved" : "Open"}>{suggestion.confidence}</Tag> {suggestion.tenantId ? tenantName(suggestion.tenantId) : ""} <span className="block text-navy/60">{suggestion.reason}</span></td>
                    <td><SmallButton tone="primary" onClick={() => match(line)}>Match…</SmallButton></td>
                  </tr>
                );
              })}
            </tbody>
          </Table>
        )}
      </Section>

      <Section title={`Unallocated receipts (${unapplied.length})`} subtitle="Cash held in unapplied receipts (account 2150) until applied to an invoice.">
        {unapplied.length === 0 ? <p className="text-sm text-navy/60">None.</p> : (
          <Table min={900}>
            <thead><tr><th>Receipt</th><th>Tenant</th><th>Received</th><th className="text-right">Unallocated</th><th>Apply to</th><th /></tr></thead>
            <tbody>
              {unapplied.map((payment) => {
                const choices = open.filter((balance) => balance.invoice.tenantId === payment.tenantId && balance.invoice.currency === payment.currency);
                const choice = applyTo[payment.id] ?? { invoiceId: choices[0]?.invoice.id ?? "", amount: "" };
                return (
                  <tr key={payment.id}>
                    <td className="font-semibold">{payment.number}</td>
                    <td>{tenantName(payment.tenantId)}</td>
                    <td>{payment.receivedDate} · {payment.reference}</td>
                    <td className="text-right tabular-nums">{money(unallocated(payment), payment.currency)}</td>
                    <td>
                      {choices.length === 0 ? <span className="text-xs text-navy/50">No open invoices for this tenant</span> : (
                        <div className="flex gap-2">
                          <select aria-label={`Apply ${payment.number} to`} className={`${inputClass} py-1 text-xs`} value={choice.invoiceId} onChange={(event) => setApplyTo({ ...applyTo, [payment.id]: { ...choice, invoiceId: event.target.value } })}>{choices.map((balance) => <option key={balance.invoice.id} value={balance.invoice.id}>{balance.invoice.number} ({money(balance.outstanding, balance.invoice.currency)})</option>)}</select>
                          <input aria-label={`Amount to apply from ${payment.number}`} type="number" step="0.01" placeholder="Amount" className={`${inputClass} w-28 py-1 text-xs`} value={choice.amount} onChange={(event) => setApplyTo({ ...applyTo, [payment.id]: { ...choice, amount: event.target.value } })} />
                        </div>
                      )}
                    </td>
                    <td>{choices.length ? <SmallButton tone="primary" onClick={() => action.run(() => arService.allocate(payment.id, [{ invoiceId: choice.invoiceId, amount: Number(choice.amount) || Math.min(unallocated(payment), choices.find((balance) => balance.invoice.id === choice.invoiceId)?.outstanding ?? 0) }], today()), "Receipt allocated.")}>Apply</SmallButton> : null}</td>
                  </tr>
                );
              })}
            </tbody>
          </Table>
        )}
      </Section>

      <Section title={`Receipts (${book.payments.length})`} subtitle="Reversals (for example a returned cheque) need a reason and approval; they post mirror-image journals and reopen the invoices.">
        {book.settings.approvals.reversals ? null : <Notice>Reversal approval is switched off in AR Settings.</Notice>}
        <Table min={1100}>
          <thead><tr><th>Receipt</th><th>Date</th><th>Tenant</th><th>Bank · method</th><th className="text-right">Amount</th><th className="text-right">Allocated</th><th className="text-right">Unallocated</th><th>Status</th><th /></tr></thead>
          <tbody>
            {book.payments.map((payment) => (
              <tr key={payment.id}>
                <td className="font-semibold">{payment.number}<span className="block text-xs font-normal text-navy/50">{payment.source.system}</span></td>
                <td>{payment.receivedDate}</td>
                <td>{tenantName(payment.tenantId)}</td>
                <td className="text-xs">{payment.bankAccount} · {payment.method} {payment.reference}</td>
                <td className="text-right tabular-nums">{money(payment.amount, payment.currency)}</td>
                <td className="text-right tabular-nums">{money(payment.amount - unallocated(payment), payment.currency)}</td>
                <td className="text-right tabular-nums">{money(unallocated(payment), payment.currency)}</td>
                <td><Tag>{payment.status}</Tag>{payment.reversal ? <span className="block text-xs text-navy/50">{payment.reversal.reason}</span> : null}</td>
                <td className="space-x-1 whitespace-nowrap">
                  <SmallButton onClick={() => download(`${payment.number}.html`, receiptHtml(book, payment), "text/html")}>Receipt</SmallButton>
                  {payment.status === "Posted" ? (
                    <>
                      <input aria-label={`Reversal reason for ${payment.number}`} placeholder="Reason" className={`${inputClass} w-28 py-1 text-xs`} value={reason[payment.id] ?? ""} onChange={(event) => setReason({ ...reason, [payment.id]: event.target.value })} />
                      <SmallButton tone="danger" onClick={() => action.run(() => arService.requestPaymentReversal(payment.id, reason[payment.id] ?? ""), `Reversal of ${payment.number} requested.`)}>Request reversal</SmallButton>
                    </>
                  ) : null}
                  {payment.status === "Reversal requested" ? (
                    <>
                      <SmallButton tone="danger" onClick={() => window.confirm(`Approve reversal of ${payment.number}? Mirror journals will be posted today.`) && action.run(() => arService.approvePaymentReversal(payment.id, today()), `${payment.number} reversed.`)}>Approve</SmallButton>
                      <SmallButton onClick={() => action.run(() => arService.cancelPaymentReversal(payment.id), "Reversal rejected.")}>Reject</SmallButton>
                    </>
                  ) : null}
                </td>
              </tr>
            ))}
          </tbody>
        </Table>
      </Section>
    </ArPage>
  );
}
