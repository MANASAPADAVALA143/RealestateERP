export const yardiCategories = categories.filter((item) => item.group !== "IFRS 16 Engine");

export function categoryById(id: CategoryId): ImportCategory {
  const found = categories.find((item) => item.id === id);
  if (!found) throw new Error(`Unknown import category: ${id}`);
  return found;
}

export function isCategoryId(value: string): value is CategoryId {
  return categories.some((item) => item.id === value);
}
